// Backup and restore of the HMS database with PostgreSQL's own tools (pg_dump / pg_restore): one custom-format file holds the platform schema and every
// hotel schema. Nothing here prints a secret: the password goes to the tools through their environment (never the command line) and messages carry names,
// sizes and counts only.
//   backup          pg_dump of the database named by the owner URL into <dir>/hms-<UTC time>.dump, plus a .sha256 beside it
//   restore-check   restores a dump into a SCRATCH database on the same server, compares it with the source and drops the scratch database again
// A real restore uses the same pg_restore against an empty database (docs/OPERATIONS.md section 4): `db:cli setup` first (the two main roles and the empty
// database), then the <dump>.roles.sql script as a superuser (the hotel roles are server-level, not in the dump), then pg_restore.
import { createHash } from "node:crypto";
import { spawn } from "node:child_process";
import { createReadStream, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { connectPg, pgWithDatabase, type DbClient } from "./pg-db";

export interface PgTools {
  /** The folder with pg_dump and pg_restore; empty = on the PATH. */
  bin: string;
}

export interface ParsedUrl {
  host: string;
  port: string;
  user: string;
  password: string;
  database: string;
}

export function parsePgUrl(url: string): ParsedUrl {
  const u = new URL(url);
  return { host: u.hostname, port: u.port || "5432", user: decodeURIComponent(u.username), password: decodeURIComponent(u.password), database: u.pathname.replace(/^\//, "") };
}

const exe = (tools: PgTools, name: string): string => (tools.bin ? path.join(tools.bin, process.platform === "win32" ? `${name}.exe` : name) : name);

function run(command: string, args: readonly string[], env: Record<string, string>): Promise<{ code: number; stderr: string }> {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { env: { ...process.env, ...env }, stdio: ["ignore", "ignore", "pipe"], windowsHide: true });
    let stderr = "";
    child.stderr.on("data", (d: Buffer) => void (stderr += d.toString()));
    child.on("error", reject);
    child.on("close", (code) => resolve({ code: code ?? 1, stderr }));
  });
}

function sha256Of(file: string): Promise<string> {
  return new Promise((resolve, reject) => {
    const hash = createHash("sha256");
    createReadStream(file).on("data", (d) => hash.update(d)).on("error", reject).on("end", () => resolve(hash.digest("hex")));
  });
}

const stamp = (now: Date): string => now.toISOString().replace(/[-:]/g, "").replace(/\.\d+Z$/, "Z");

/**
 * The hotel roles belong to the whole server, not to one database, so a dump does not carry them. This script (run by a superuser before pg_restore on a NEW
 * server) makes each hotel's login-less role if it is missing and lets the app and the owner become it, exactly as hotel creation does. Safe to run twice.
 */
export async function hotelRolesScript(db: DbClient, appRole = "hms_app", ownerRole = "hms_owner"): Promise<string> {
  // a hotel's schema is named for the hotel since migration 0172 but its role is still hotel_<id>_rw (platform.hotels.role_name): the hotels' own list names the roles of the schemas that
  // exist, and a schema still called hotel_<hex> (not renamed yet) names its role by the old rule
  const listed = await db.query("SELECT h.role_name AS r FROM platform.hotels h JOIN pg_namespace n ON n.nspname = h.schema_name").then((x) => x.rows.map((r) => String(r.r)), () => [] as string[]);
  const legacy = (await db.query("SELECT nspname || '_rw' AS r FROM pg_namespace WHERE nspname ~ '^hotel_[0-9a-f]{32}$'")).rows.map((r) => String(r.r));
  const roles = [...new Set([...listed, ...legacy])].sort();
  const lines = ["-- hotel roles for the dump next to this file (generated by db:cli backup); run as a PostgreSQL superuser BEFORE pg_restore on a new server"];
  for (const role of roles) {
    if (!/^hotel_[0-9a-f]{32}_rw$/.test(role) || !/^[a-z_]+$/.test(appRole + ownerRole)) throw new Error("unexpected role name");
    lines.push(`DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${role}') THEN CREATE ROLE "${role}" NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS; END IF; END $$;`);
    lines.push(`GRANT "${role}" TO ${appRole} WITH INHERIT FALSE, SET TRUE;`);
    lines.push(`GRANT "${role}" TO ${ownerRole} WITH ADMIN OPTION, INHERIT FALSE, SET TRUE;`);
  }
  return `${lines.join("\n")}\n`;
}

/**
 * The pg_dump arguments of a backup. Rows left out (the tables themselves are kept): every Conversations table (decision 66:
 * guests' messages, addresses and numbers, in each hotel schema and in the platform schema) so nothing personal sits in a backup in plain form. The personal mailboxes of the staff
 * (platform.pmail_*, platform 0178 and 0179) are left out the same way, and they also have FORCED row security, which makes pg_dump refuse such a table's rows altogether (3 Nov 2026).
 */
// `schemas`: only these schemas are dumped (a hosted database such as Supabase has its own auth, storage and realtime schemas that the owner login may not read, and that are not ours).
export function pgDumpArgs(p: { host: string; port: string; user: string; database: string }, file: string, schemas: readonly string[] = []): string[] {
  return ["--host", p.host, "--port", p.port, "--username", p.user, "--dbname", p.database, "--format=custom", "--no-password", "--exclude-table-data=*.conv_*", "--exclude-table-data=*.group_conv_*", "--exclude-table-data=*.pmail_*", ...schemas.flatMap((s) => ["--schema", s]), "--file", file];
}

/** The schemas of this application: platform and every hotel's own (the hotels' list names them since migration 0172; a schema still called hotel_<hex> counts too). */
export async function ourSchemas(db: DbClient): Promise<string[]> {
  const listed = await db.query("SELECT schema_name AS s FROM platform.hotels WHERE provisioned_at IS NOT NULL AND deleted_at IS NULL").then((x) => x.rows.map((r) => String(r.s)), () => [] as string[]);
  const found = (await db.query("SELECT nspname AS s FROM pg_namespace WHERE nspname = ANY($1::text[]) OR nspname ~ '^hotel_[0-9a-f]{32}$' ORDER BY 1", [listed])).rows.map((r) => String(r.s));
  return ["platform", ...found.filter((s) => s !== "platform")];
}

/** Dumps the database. Returns the file and its size and checksum (and writes the hotel-roles script beside it). */
export async function backupDatabase(options: { url: string; dir: string; tools: PgTools; now?: Date }): Promise<{ file: string; bytes: number; sha256: string }> {
  const p = parsePgUrl(options.url);
  mkdirSync(options.dir, { recursive: true });
  const file = path.join(options.dir, `hms-${stamp(options.now ?? new Date())}.dump`);
  const probe = await connectPg(options.url);
  let schemas: string[];
  try {
    schemas = await ourSchemas(probe);
  } finally {
    await probe.end();
  }
  const r = await run(exe(options.tools, "pg_dump"), pgDumpArgs(p, file, schemas), { PGPASSWORD: p.password });
  if (r.code !== 0) throw new Error(`pg_dump failed (exit ${r.code}): ${r.stderr.trim().split(/\r?\n/).slice(0, 3).join(" | ").slice(0, 600)}`);
  const sha256 = await sha256Of(file);
  writeFileSync(`${file}.sha256`, `${sha256}  ${path.basename(file)}\n`, "utf8");
  const source = await connectPg(options.url);
  try {
    writeFileSync(`${file}.roles.sql`, await hotelRolesScript(source), "utf8");
  } finally {
    await source.end();
  }
  return { file, bytes: statSync(file).size, sha256 };
}

export interface Snapshot {
  platformUsers: number;
  platformHotels: number;
  hotelSchemas: number;
  /** Rows in a few tables of every hotel schema, summed: a cheap fingerprint. */
  hotelRows: number;
}

const FINGERPRINT_TABLES = ["bill_master_bills", "bill_master_advances", "pms_stays", "customers", "company_profiles", "employees"];

export async function snapshotOf(db: DbClient): Promise<Snapshot> {
  const count = async (sql: string): Promise<number> => Number((await db.query(sql)).rows[0].n);
  // the hotels' own list says which schemas are theirs (readable names, migration 0172); a schema still called hotel_<hex> counts too
  const listed = await db.query("SELECT schema_name AS s FROM platform.hotels WHERE provisioned_at IS NOT NULL AND deleted_at IS NULL").then((x) => x.rows.map((r) => String(r.s)), () => [] as string[]);
  const schemas = (await db.query("SELECT nspname AS s FROM pg_namespace WHERE nspname = ANY($1::text[]) OR nspname ~ '^hotel_[0-9a-f]{32}$' ORDER BY 1", [listed])).rows.map((r) => String(r.s));
  let hotelRows = 0;
  for (const s of schemas) for (const t of FINGERPRINT_TABLES) hotelRows += await count(`SELECT count(*) AS n FROM "${s}"."${t}"`).catch(() => 0);
  return {
    platformUsers: await count("SELECT count(*) AS n FROM platform.people"),
    platformHotels: await count("SELECT count(*) AS n FROM platform.hotels"),
    hotelSchemas: schemas.length,
    hotelRows,
  };
}

/**
 * Proves a dump can be restored: restores it into a scratch database next to the source, compares a fingerprint with the source and drops the scratch
 * database again. `superUrl` is a server-level login that may create and drop databases; `ownerUrl` is the source database's owner.
 */
export async function restoreCheck(options: { file: string; superUrl: string; ownerUrl: string; tools: PgTools; scratch?: string }): Promise<{ source: Snapshot; restored: Snapshot; same: boolean; warnings: number }> {
  const scratch = options.scratch ?? "hms_restore_check";
  if (!/^[a-z0-9_]+$/.test(scratch) || scratch === parsePgUrl(options.ownerUrl).database) throw new Error("the scratch database needs its own plain name");
  const sup = parsePgUrl(options.superUrl);
  const admin = await connectPg(options.superUrl);
  const source = await connectPg(options.ownerUrl);
  try {
    await admin.query(`DROP DATABASE IF EXISTS "${scratch}"`);
    await admin.query(`CREATE DATABASE "${scratch}"`);
    // a hosted database (Supabase) has no built-in uuidv7(): its tables default to public.uuidv7(), a function of the public schema that a dump of our schemas does not carry. The scratch
    // copy gets the same name from this server's own uuidv7() so the tables can be made (a restore into the hosted project itself finds its own).
    const prepared = await connectPg(pgWithDatabase(options.superUrl, scratch));
    try {
      await prepared.query("DO $$ BEGIN IF to_regprocedure('public.uuidv7()') IS NULL AND to_regprocedure('pg_catalog.uuidv7()') IS NOT NULL THEN CREATE FUNCTION public.uuidv7() RETURNS uuid LANGUAGE sql AS 'SELECT pg_catalog.uuidv7()'; END IF; END $$");
    } finally {
      await prepared.end();
    }
    // the hotel roles first, from the script written beside the dump (what a restore on a new server does); a missing script is not an error here
    if (existsSync(`${options.file}.roles.sql`)) await admin.query(readFileSync(`${options.file}.roles.sql`, "utf8"));
    const restored = await run(exe(options.tools, "pg_restore"), ["--host", sup.host, "--port", sup.port, "--username", sup.user, "--dbname", scratch, "--no-owner", "--no-password", options.file], { PGPASSWORD: sup.password });
    const warnings = restored.stderr.split(/\r?\n/).filter((l) => l.includes("error:")).length;
    const targetUrl = new URL(options.superUrl);
    targetUrl.pathname = `/${scratch}`;
    const copy = await connectPg(targetUrl.toString());
    try {
      const a = await snapshotOf(source);
      const b = await snapshotOf(copy);
      return { source: a, restored: b, same: JSON.stringify(a) === JSON.stringify(b), warnings };
    } finally {
      await copy.end();
    }
  } finally {
    await source.end();
    await admin.query(`DROP DATABASE IF EXISTS "${scratch}"`).catch(() => undefined);
    await admin.end();
  }
}

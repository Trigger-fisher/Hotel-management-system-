// Generates db/seeds/hotel/0001_defaults.sql from db/seeds/source/pallav-hotel-defaults.json: the structural defaults every
// new hotel starts with (shifts, payment modes, plans, contact roles, exit types, ID proof types, expense heads, business units).
//   Write the file:     npx tsx db/scripts/generate-hotel-seeds.ts
//   Check for drift:    npx tsx db/scripts/generate-hotel-seeds.ts --check      (also run by tests/server/seeds.hotel.test.ts)
// The SQL is idempotent (INSERT ... ON CONFLICT DO NOTHING), unqualified (it runs with the hotel schema first on search_path)
// and holds no real person, phone number, e-mail, bank detail or Hotel Pallav text.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

interface BusinessUnit { slug: string; name: string; code: string; accent: string; icon: string; sortOrder: number }
interface OptionSet { key: string; name: string; description: string; icon: string; input: string; source: string; items: string[] }
interface Defaults {
  businessUnits: { source: string; rows: BusinessUnit[] };
  optionSets: OptionSet[];
  expenseCategories: { source: string; businesses: string[]; names: string[] };
  idProofTypes: { source: string; names: string[] };
  payrollMasterItems: { source: string; lists: { list: string; labels: string[] }[] };
  payrollCompanies: { source: string; rows: { code: string; nameSuffix: string }[] };
  appSettings: { source: string; rows: { key: string; value: string }[] };
  singletonRows: { source: string; tables: string[] };
}

const text = (value: string): string => `'${value.replace(/'/g, "''")}'`;

export function generateHotelSeed(d: Defaults): string {
  const units = d.businessUnits.rows.map((u) => `  (${[text(u.name), text(u.slug), text(u.code), text(u.accent), text(u.icon), "true", String(u.sortOrder)].join(", ")})`);
  const sets = d.optionSets.map((s, i) => `  (${[text(s.key), text(s.name), text(s.description), text(s.icon), text(s.input), "true", String(i + 1)].join(", ")})`);
  const items = d.optionSets.flatMap((s) => s.items.map((label, i) => `  (${[text(s.key), text(label), i === 0 ? "true" : "false", String(i + 1)].join(", ")})`));
  const categories = d.expenseCategories.businesses.flatMap((b) => d.expenseCategories.names.map((n, i) => `  (${[text(b), text(n), String(i + 1)].join(", ")})`));
  const proofs = d.idProofTypes.names.map((n) => `  (${text(n)})`);
  const master = d.payrollMasterItems.lists.flatMap((l) => l.labels.map((label, i) => `  (${[text(l.list), text(label), String(i + 1)].join(", ")})`));
  // the hotel's name is handed in by create-hotel as the session setting hms.hotel_name; without it current_setting() fails and nothing is seeded
  const companies = d.payrollCompanies.rows.map((r) => `  (${[r.nameSuffix === "" ? "current_setting('hms.hotel_name')" : `current_setting('hms.hotel_name') || ${text(r.nameSuffix)}`, text(r.code)].join(", ")})`);
  const settings = d.appSettings.rows.map((r) => `  (${[text(r.key), text(r.value), "false"].join(", ")})`);
  const singletons = d.singletonRows.tables.map((t) => `INSERT INTO ${t} DEFAULT VALUES ON CONFLICT DO NOTHING;`);

  return `-- seed: structural defaults for every new hotel (business units, master lists, expense heads, ID proof types, payroll lists, the two single-row website tables)
-- GENERATED by db/scripts/generate-hotel-seeds.ts from db/seeds/source/pallav-hotel-defaults.json (each list names its Pallav source there).
-- Do not edit by hand: change the generator or the source and add a NEW seed file; an applied seed file is immutable.
-- Only structure: no real people, phone numbers, e-mails, bank data or Hotel Pallav text. Idempotent: running it twice changes nothing.

-- business units: ${d.businessUnits.source}
INSERT INTO business_units (name, slug, code, accent, icon, is_active, sort_order)
VALUES
${units.join(",\n")}
ON CONFLICT (slug) DO NOTHING;

-- master lists (option sets)
INSERT INTO option_sets (key, name, description, icon, input, is_system, sort_order)
VALUES
${sets.join(",\n")}
ON CONFLICT (key) DO NOTHING;

-- the entries of those lists (the first of each list is its default)
INSERT INTO option_items (option_set_id, label, value, is_default, sort_order)
SELECT s.id, v.label, v.label, v.is_default, v.sort_order
FROM (VALUES
${items.join(",\n")}
) AS v (set_key, label, is_default, sort_order)
JOIN option_sets s ON s.key = v.set_key
ON CONFLICT (option_set_id, value) DO NOTHING;

-- expense categories for both businesses: ${d.expenseCategories.source}
INSERT INTO expense_categories (business, name, sort_order)
VALUES
${categories.join(",\n")}
ON CONFLICT (business, name) DO NOTHING;

-- ID proof types: ${d.idProofTypes.source}
INSERT INTO id_proof_types (name)
VALUES
${proofs.join(",\n")}
ON CONFLICT (name) DO NOTHING;

-- payroll master lists shared by every company: ${d.payrollMasterItems.source}
INSERT INTO payroll_master_items (list, label, sort_order)
VALUES
${master.join(",\n")}
ON CONFLICT (list, label) WHERE payroll_company_id IS NULL DO NOTHING;

-- the two fixed payroll companies, named after the hotel (hms.hotel_name is set by create-hotel): ${d.payrollCompanies.source}
INSERT INTO payroll_companies (name, code)
VALUES
${companies.join(",\n")}
ON CONFLICT (code) DO NOTHING;

-- the settings the code reads (a hotel changes them on screen): ${d.appSettings.source}
INSERT INTO app_settings (key, value, is_secret)
VALUES
${settings.join(",\n")}
ON CONFLICT (key) DO NOTHING;

-- the single website rows (only the column defaults): ${d.singletonRows.source}
${singletons.join("\n")}
`;
}

const root = path.join(__dirname, "..");
export const HOTEL_SEED_SOURCE = path.join(root, "seeds", "source", "pallav-hotel-defaults.json");
export const HOTEL_SEED_OUTPUT = path.join(root, "seeds", "hotel", "0001_defaults.sql");

export function loadHotelDefaults(): Defaults {
  return JSON.parse(readFileSync(HOTEL_SEED_SOURCE, "utf8")) as Defaults;
}

if (require.main === module) {
  const sql = generateHotelSeed(loadHotelDefaults());
  if (process.argv.includes("--check")) {
    const same = readFileSync(HOTEL_SEED_OUTPUT, "utf8") === sql;
    process.stdout.write(same ? "Hotel seeds are up to date\n" : "Hotel seeds are OUT OF DATE: run npx tsx db/scripts/generate-hotel-seeds.ts\n");
    process.exit(same ? 0 : 1);
  }
  writeFileSync(HOTEL_SEED_OUTPUT, sql);
  process.stdout.write(`Wrote ${HOTEL_SEED_OUTPUT}\n`);
}

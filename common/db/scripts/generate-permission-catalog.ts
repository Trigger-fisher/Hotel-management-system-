// Generates web-app/src/server/auth/catalog.generated.ts: for every module, part and one-off ability of Pallav's permission list,
// the highest of MJ's four levels it offers. The permission engine caps a person's level on a part by this (effective level =
// min(granted level, level offered)), so a part that only offers View and Edit can never be "Create".
//   Write the file:     npx tsx db/scripts/generate-permission-catalog.ts
//   Check for drift:    npx tsx db/scripts/generate-permission-catalog.ts --check     (also run by npm run seeds:check)
//
// Sources: db/seeds/source/pallav-permissions.json (exported from app/Support/Permissions.php), the same file the platform seed uses, then
// db/seeds/source/hms-permissions.json: HMS's own modules that Pallav does not have (Conversations, decision 66; its row and grants come from
// platform migration 0139 and seed 0003_hms_permissions). A key in both lists is a mistake and stops the generator.
// Offered level: the highest rank among the actions a module or part offers, where view = 1, create = 2, edit = 3, delete = 4 (full).
// "export" (PDF/print) never raises it: it is folded into view, exactly as in generate-platform-seeds.ts. A one-off ability is on or
// off: it offers "full".
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

export type Level = "view" | "create" | "edit" | "full";
const RANK: Record<string, number> = { view: 1, create: 2, edit: 3, delete: 4 };
const LEVEL_BY_RANK: Record<number, Level> = { 1: "view", 2: "create", 3: "edit", 4: "full" };

interface Item {
  key: string;
  actions: string[];
}
interface Source {
  modules: (Item & { parts: Item[] })[];
  abilities: { key: string }[];
}

export interface CatalogEntry {
  key: string;
  kind: "module" | "part" | "ability";
  parent: string | null;
  offers: Level;
}

export function offeredLevel(actions: readonly string[]): Level {
  const rank = Math.max(1, ...actions.map((a) => RANK[a] ?? 0));
  return LEVEL_BY_RANK[rank];
}

export function buildCatalog(source: Source): CatalogEntry[] {
  const entries: CatalogEntry[] = [];
  for (const m of source.modules) {
    entries.push({ key: m.key, kind: "module", parent: null, offers: offeredLevel(m.actions) });
    for (const p of m.parts) entries.push({ key: p.key, kind: "part", parent: m.key, offers: offeredLevel(p.actions) });
  }
  for (const a of source.abilities) entries.push({ key: a.key, kind: "ability", parent: null, offers: "full" });
  return entries;
}

export function renderCatalog(entries: readonly CatalogEntry[]): string {
  const rows = entries.map((e) => `  { key: ${JSON.stringify(e.key)}, kind: ${JSON.stringify(e.kind)}, parent: ${JSON.stringify(e.parent)}, offers: ${JSON.stringify(e.offers)} },`);
  return [
    'import "server-' + 'only";',
    "// GENERATED by db/scripts/generate-permission-catalog.ts from db/seeds/source/pallav-permissions.json and db/seeds/source/hms-permissions.json. Do not edit by hand:",
    "// change the generator or the source and run it again (npm run seeds:check fails when this file is out of date).",
    'import type { CatalogEntry } from "./catalog";',
    "",
    "export const PERMISSION_CATALOG: readonly CatalogEntry[] = [",
    ...rows,
    "];",
    "",
  ].join("\n");
}

const root = path.join(__dirname, "..", "..", "..");
const sourceFile = path.join(root, "common", "db", "seeds", "source", "pallav-permissions.json");
const hmsSourceFile = path.join(root, "common", "db", "seeds", "source", "hms-permissions.json");
export const CATALOG_FILE = path.join(root, "web-app", "src", "server", "auth", "catalog.generated.ts");

/** Pallav's list, then HMS's own after it; the same key twice throws. */
export function mergeSources(pallav: Source, hms: Source): Source {
  const seen = new Set<string>();
  const keyOf = (k: string): string => {
    if (seen.has(k)) throw new Error(`Permission key "${k}" is in both pallav-permissions.json and hms-permissions.json`);
    seen.add(k);
    return k;
  };
  for (const m of [...pallav.modules, ...hms.modules]) {
    keyOf(m.key);
    for (const p of m.parts) keyOf(p.key);
  }
  for (const a of [...pallav.abilities, ...hms.abilities]) keyOf(a.key);
  return { modules: [...pallav.modules, ...hms.modules], abilities: [...pallav.abilities, ...hms.abilities] };
}

export function expectedCatalogText(): string {
  const read = (file: string): Source => JSON.parse(readFileSync(file, "utf8")) as Source;
  return renderCatalog(buildCatalog(mergeSources(read(sourceFile), read(hmsSourceFile))));
}

if (require.main === module) {
  const text = expectedCatalogText();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(CATALOG_FILE, "utf8").replace(/\r\n/g, "\n");
    } catch {
      current = "";
    }
    if (current !== text) {
      process.stderr.write("Permission catalog is out of date: run npx tsx db/scripts/generate-permission-catalog.ts\n");
      process.exit(1);
    }
    process.stdout.write("Permission catalog is up to date\n");
  } else {
    writeFileSync(CATALOG_FILE, text, "utf8");
    process.stdout.write(`Wrote ${path.relative(root, CATALOG_FILE)}\n`);
  }
}

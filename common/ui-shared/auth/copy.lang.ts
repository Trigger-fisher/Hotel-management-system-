/** "15 minutes" / "1 minute" in the language (the {minutes} of the locked screen). Digits stay Latin. */
/** (French and German have no words for this screen yet, so its sentence stays English and so does the minutes text.) */
export function minutesTextIn(seconds: number, language: Language): string {
  const m = Math.max(1, Math.ceil(seconds / 60));
  if (language === 'hi') return `${m} मिनट`;
  if (language === 'gu') return `${m} મિનિટ`;
  return m === 1 ? '1 minute' : `${m} minutes`;
}

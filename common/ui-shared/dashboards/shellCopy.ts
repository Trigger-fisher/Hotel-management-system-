export const shellCopyByLanguage = copyByLanguage(shellCopy, shellCopyHi, shellCopyGu, shellCopyFr, shellCopyDe);

/** English menu text of a portal to its key in shellCopy.nav, built once from the English words (the menu itself in nav.ts is not changed). */
const NAV_KEY_BY_TEXT: ReadonlyMap<string, keyof typeof shellCopy.nav> = new Map(
  (Object.keys(shellCopy.nav) as (keyof typeof shellCopy.nav)[]).map((k) => [shellCopy.nav[k], k]),
);

/** A menu group name, an item name or a page title in the language; any text that is not one of the portal words comes back unchanged (staff menus stay English for now). */
export function translateNavText(text: string, language: Language): string {
  if (language === 'en') return text;
  const key = NAV_KEY_BY_TEXT.get(text);
  return key ? pickCopy(shellCopyByLanguage, language).nav[key] : text;
}

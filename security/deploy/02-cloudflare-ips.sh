#!/usr/bin/env bash
# Lets ONLY Cloudflare reach the web port (security plan 2026-11-01, section 5), and tells nginx which addresses are Cloudflare's so it can see the real visitor.
# Reads Cloudflare's published lists (https://www.cloudflare.com/ips), checks every line, then:
#   - writes /etc/nginx/cloudflare-realip.conf   (set_real_ip_from for each range; included by nginx/hms.conf)
#   - adds UFW rules: 443/tcp from each range (port 80 is not opened: Cloudflare reaches the origin on 443 with SSL mode Full strict)
# Run it again whenever Cloudflare changes its ranges (they change rarely; a monthly cron is enough). It only ADDS rules; to remove an old range, use `ufw status numbered`.
# NOT RUN ANYWHERE YET. Nothing changes without --apply.
set -euo pipefail
APPLY=0; [ "${1:-}" = "--apply" ] && APPLY=1
die() { echo "STOP: $*" >&2; exit 1; }
[ "$APPLY" = 0 ] || [ "$(id -u)" = 0 ] || die "--apply needs root (sudo)"

V4="$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4)" || die "could not download the IPv4 list"
V6="$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6)" || die "could not download the IPv6 list"
RE4='^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$'
RE6='^[0-9a-fA-F:]+/[0-9]{1,3}$'
n4=0; n6=0
while IFS= read -r l; do [ -z "$l" ] && continue; [[ "$l" =~ $RE4 ]] || die "unexpected line in the IPv4 list: $l"; n4=$((n4 + 1)); done <<<"$V4"
while IFS= read -r l; do [ -z "$l" ] && continue; [[ "$l" =~ $RE6 ]] || die "unexpected line in the IPv6 list: $l"; n6=$((n6 + 1)); done <<<"$V6"
# a truncated or replaced answer must not lock the site out or open it up
[ "$n4" -ge 8 ] && [ "$n6" -ge 3 ] || die "the lists look too short ($n4 IPv4, $n6 IPv6 ranges): not changing anything"

CONF=/etc/nginx/cloudflare-realip.conf
tmp="$(mktemp)"
{
  echo "# generated by security/deploy/02-cloudflare-ips.sh from https://www.cloudflare.com/ips"
  while IFS= read -r l; do [ -n "$l" ] && echo "set_real_ip_from $l;"; done <<<"$V4"
  while IFS= read -r l; do [ -n "$l" ] && echo "set_real_ip_from $l;"; done <<<"$V6"
  echo "real_ip_header CF-Connecting-IP;"
} > "$tmp"

if [ "$APPLY" = 1 ]; then
  install -m 644 "$tmp" "$CONF"
  while IFS= read -r l; do [ -n "$l" ] && ufw allow proto tcp from "$l" to any port 443 >/dev/null; done <<<"$V4"
  while IFS= read -r l; do [ -n "$l" ] && ufw allow proto tcp from "$l" to any port 443 >/dev/null; done <<<"$V6"
  echo "wrote $CONF and $((n4 + n6)) firewall rules. Check: ufw status | head; nginx -t && systemctl reload nginx"
else
  echo "(dry run) would write $CONF with $((n4 + n6)) ranges and open 443/tcp for each in UFW:"
  cat "$tmp"
fi
rm -f "$tmp"
